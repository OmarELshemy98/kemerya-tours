export function getLocalePath(locale: Locale, path = "") {
  const normalizedPath = path.startsWith("/") ? path : `/${path}`;
  if (locale === defaultLocale) {
    return normalizedPath || "/en";
  }
  return `/${locale}${normalizedPath || ""}`;
}

